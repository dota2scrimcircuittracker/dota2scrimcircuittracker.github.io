// Regenerate public/lib/items-data.js from OpenDota's item constants (run after a patch adds items).
// Usage: node scripts/gen/gen-item-meta.js
import { writeFile } from "node:fs/promises";

const get = async (p) => (await fetch(`https://api.opendota.com/api/constants/${p}`)).json();
const [items, ids] = await Promise.all([get("items"), get("item_ids")]);

// kind: b = built from components, c = consumable, r = recipe, n = neutral item, "" = plain shop item.
const kind = (key, it) => (key.startsWith("recipe_") ? "r" : it.tier != null && !it.cost ? "n" : it.qual === "consumable" ? "c" : it.components ? "b" : "");
const slug = (img) => (img ?? "").replace(/^.*\/items\//, "").replace(/\.png.*$/, "");
const rows = Object.fromEntries(Object.entries(items).filter(([, it]) => it.dname)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([key, it]) => [key, [it.dname, it.cost ?? 0, slug(it.img) === key ? 0 : slug(it.img), kind(key, it), ...(it.components ? [[...new Set(it.components)]] : [])]]));
const idMap = Object.fromEntries(Object.entries(ids).filter(([, k]) => rows[k]).map(([id, k]) => [id, k]));

const src = `// Generated by scripts/gen/gen-item-meta.js from OpenDota /constants/items and /constants/item_ids.
// ITEMS: key -> [display name, cost, icon slug (0 = same as key), kind, components?]; kind b = built
// from components, c = consumable, r = recipe, n = neutral, "" = plain shop item. ITEM_IDS: id -> key.
export const ITEMS = ${JSON.stringify(rows)};
export const ITEM_IDS = ${JSON.stringify(idMap)};
`;
await writeFile(new URL("../../public/lib/items-data.js", import.meta.url), src);
console.log(`wrote public/lib/items-data.js (${Object.keys(rows).length} items, ${Object.keys(idMap).length} ids)`);
