// Regenerate public/lib/abilities-data.js from OpenDota's ability constants (run after a patch
// adds heroes or abilities). Only abilities a hero can level are kept: the ids skill builds use.
// Usage: node scripts/gen/gen-ability-meta.js
import { writeFile } from "node:fs/promises";

const get = async (p) => (await fetch(`https://api.opendota.com/api/constants/${p}`)).json();
const [abilities, ids, heroAbilities] = await Promise.all([get("abilities"), get("ability_ids"), get("hero_abilities")]);

// Every ability listed on a hero, plus every talent (some talents are missing from
// hero_abilities). OpenDota's talent names keep a {s:value} template without the value, so the
// template and its sign go: "-{s:bonus_AbilityCooldown}s Meat Hook Cooldown" -> "Meat Hook
// Cooldown". Talents with no name get one from their key.
const onHero = new Set(Object.values(heroAbilities).flatMap((h) => [...(h.abilities ?? []), ...(h.talents ?? []).map((t) => t.name)]));
const talent = (key) => key.startsWith("special_bonus");
const nameOf = (key) => {
  const dname = abilities[key]?.dname;
  if (key === "special_bonus_attributes") return "Attributes";
  if (!dname) return talent(key) ? key.replace(/^special_bonus_(unique_)?/, "").replace(/_/g, " ").replace(/^\w/, (c) => c.toUpperCase()) : null;
  return talent(key) ? dname.replace(/\{s:[^}]+\}/g, "").replace(/^[+-]?\s*(s|%|x)?\s+/, "").replace(/\s+/g, " ").trim() || dname : dname;
};
const rows = Object.fromEntries(Object.entries(ids)
  .filter(([, key]) => (onHero.has(key) || talent(key)) && nameOf(key))
  .sort(([a], [b]) => Number(a) - Number(b))
  .map(([id, key]) => [id, [key, nameOf(key)]]));

const src = `// Generated by scripts/gen/gen-ability-meta.js from OpenDota /constants/abilities, /ability_ids and
// /hero_abilities. ABILITIES: ability id -> [key, display name]; talents' keys start "special_bonus".
export const ABILITIES = ${JSON.stringify(rows)};
`;
await writeFile(new URL("../../public/lib/abilities-data.js", import.meta.url), src);
console.log(`wrote public/lib/abilities-data.js (${Object.keys(rows).length} abilities)`);
