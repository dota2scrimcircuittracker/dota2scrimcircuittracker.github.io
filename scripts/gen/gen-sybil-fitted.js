// Regenerates public/lib/sybil-fitted.js from Project Sybil's fitted draft model
// (ybabts/Project-Sybil, packages/sybil/fitted/cmDraft.json and cmRoleShares.json): the model's
// weights, the pool parameters, the population's hero-by-position shares, and the lane-parsed
// position table the role filter reads. Run after Sybil refits:
//   node scripts/gen/gen-sybil-fitted.js <path to a Project-Sybil checkout>
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const repo = process.argv[2];
if (!repo) throw new Error("usage: node scripts/gen/gen-sybil-fitted.js <Project-Sybil checkout>");
const j = JSON.parse(await readFile(path.join(repo, "packages/sybil/fitted/cmDraft.json"), "utf8"));
// The lane-parsed position table the role filter reads (cmRoleShares.json), separate from the
// model's own shares: those were fitted into the assignment and can't separate a carry from a support.
const lane = JSON.parse(await readFile(path.join(repo, "packages/sybil/fitted/cmRoleShares.json"), "utf8"));
const out = {
  weights: { intercept: j.weights.intercept, slopes: j.weights.slopes },
  pool: j.pool,
  roles: { from: j.roles.from, to: j.roles.to, games: j.roles.games, shares: j.roles.shares },
  laneRoles: { from: lane.from, to: lane.to, games: lane.games, shares: lane.shares },
  provenance: j.provenance,
};
const file = path.join(import.meta.dirname, "../../public/lib/sybil-fitted.js");
await writeFile(file, `// Generated by scripts/gen/gen-sybil-fitted.js from Project Sybil's packages/sybil/fitted/cmDraft.json
// (ybabts). Do not edit by hand.
export default ${JSON.stringify(out)};
`);
console.log(`wrote ${path.relative(process.cwd(), file)} (fitted ${j.provenance?.fitted}, ${Object.keys(j.roles.shares).length} heroes)`);
